    residencial_id      bigint NOT NULL REFERENCES residenciales (id),
    codigo              varchar(30) NOT NULL,
    tipo                varchar(20) NOT NULL CHECK (tipo IN ('casa', 'apartamento')),
    edificio_torre      varchar(60),
    calle_bloque        varchar(60),
    numero              varchar(20),
    estado_ocupacion    varchar(20) NOT NULL DEFAULT 'ocupada'
