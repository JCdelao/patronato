-- ===================================================================
-- E10 · Guardias y turnos
-- ===================================================================

CREATE TABLE guardias (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id  bigint NOT NULL REFERENCES residenciales (id),
    user_id         bigint UNIQUE REFERENCES users (id),
    nombre          varchar(150) NOT NULL,
    identidad       varchar(30) NOT NULL,
    telefono        varchar(30),
    activo          boolean NOT NULL DEFAULT true,
    created_at      timestamp(0),
    updated_at      timestamp(0),
    UNIQUE (residencial_id, identidad),
    UNIQUE (residencial_id, id)
);

CREATE TABLE turnos (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id  bigint NOT NULL,
    guardia_id      bigint NOT NULL,
    inicio          timestamp(0) NOT NULL,
    fin             timestamp(0) NOT NULL,
    inicio_real     timestamp(0),
    created_at      timestamp(0),
    updated_at      timestamp(0),
    FOREIGN KEY (residencial_id, guardia_id) REFERENCES guardias (residencial_id, id),
    UNIQUE (residencial_id, id),
    CHECK (fin > inicio),
    EXCLUDE USING gist (guardia_id WITH =, tsrange(inicio, fin) WITH &&)
);

CREATE INDEX turnos_residencial_inicio_index ON turnos (residencial_id, inicio);

CREATE TABLE entregas_turno (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id      bigint NOT NULL,
    turno_id            bigint NOT NULL UNIQUE,
    guardia_entrega_id  bigint NOT NULL,
    guardia_recibe_id   bigint NOT NULL,
    entregado_en        timestamp(0) NOT NULL,
    novedades           text,
    recibido_en         timestamp(0),
    created_at          timestamp(0),
    updated_at          timestamp(0),
    FOREIGN KEY (residencial_id, turno_id) REFERENCES turnos (residencial_id, id),
    FOREIGN KEY (residencial_id, guardia_entrega_id) REFERENCES guardias (residencial_id, id),
    FOREIGN KEY (residencial_id, guardia_recibe_id) REFERENCES guardias (residencial_id, id)
);

CREATE TABLE tipos_incidencia (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id  bigint NOT NULL REFERENCES residenciales (id),
    nombre          varchar(80) NOT NULL,
    activo          boolean NOT NULL DEFAULT true,
    UNIQUE (residencial_id, nombre),
    UNIQUE (residencial_id, id)
);

CREATE TABLE incidencias (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id      bigint NOT NULL,
    tipo_incidencia_id  bigint NOT NULL,
    guardia_id          bigint NOT NULL,
    turno_id            bigint,
    descripcion         text NOT NULL,
    ocurrida_en         timestamp(0) NOT NULL,
    foto_path           varchar(255),
    urgente             boolean NOT NULL DEFAULT false,
    created_at          timestamp(0),
    updated_at          timestamp(0),
    FOREIGN KEY (residencial_id, tipo_incidencia_id) REFERENCES tipos_incidencia (residencial_id, id),
    FOREIGN KEY (residencial_id, guardia_id) REFERENCES guardias (residencial_id, id),
    FOREIGN KEY (residencial_id, turno_id) REFERENCES turnos (residencial_id, id)
);

CREATE INDEX incidencias_residencial_fecha_index ON incidencias (residencial_id, ocurrida_en);

