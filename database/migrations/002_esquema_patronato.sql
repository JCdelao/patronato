CREATE INDEX vivienda_residentes_residente_id_index ON vivienda_residentes (residente_id);

-- Como máximo un responsable de pago vigente por vivienda; la aplicación exige que exista uno (HU-11).
CREATE UNIQUE INDEX vivienda_un_responsable_unique
    ON vivienda_residentes (vivienda_id)
    WHERE es_responsable_pago AND fecha_fin IS NULL;

CREATE UNIQUE INDEX vivienda_residente_vigente_unique
    ON vivienda_residentes (vivienda_id, residente_id)
    WHERE fecha_fin IS NULL;

-- ===================================================================
-- E04 · Parámetros de cobro
-- ===================================================================

-- La modalidad vigente de un período es la de mayor vigente_desde <= período (HU-14).
CREATE TABLE modalidades_cobro (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id  bigint NOT NULL REFERENCES residenciales (id),
    modalidad       varchar(20) NOT NULL CHECK (modalidad IN ('unificada', 'diversificada')),
    vigente_desde   date NOT NULL CHECK (EXTRACT(DAY FROM vigente_desde) = 1),
    created_by      bigint REFERENCES users (id),
    created_at      timestamp(0),
    UNIQUE (residencial_id, vigente_desde)
);

-- En modalidad unificada solo se cobra el concepto con es_cuota_unificada;
-- las tarifas de los demás son el desglose informativo.
CREATE TABLE conceptos_cobro (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id      bigint NOT NULL REFERENCES residenciales (id),
    nombre              varchar(100) NOT NULL,
    tipo                varchar(20) NOT NULL CHECK (tipo IN ('recurrente', 'unico')),
    es_cuota_unificada  boolean NOT NULL DEFAULT false,
    activo              boolean NOT NULL DEFAULT true,
    created_at          timestamp(0),
    updated_at          timestamp(0),
    UNIQUE (residencial_id, nombre),
    UNIQUE (residencial_id, id)
);

-- Sin tipo_vivienda ni vivienda_id, la tarifa aplica a todas.
-- La tarifa especial (vivienda_id) prevalece sobre la del tipo (HU-16).
CREATE TABLE tarifas (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id  bigint NOT NULL,
    concepto_id     bigint NOT NULL,
    tipo_vivienda   varchar(20) CHECK (tipo_vivienda IN ('casa', 'apartamento')),
    vivienda_id     bigint,
    monto           numeric(12, 2) NOT NULL CHECK (monto >= 0),
    vigente_desde   date NOT NULL,
    vigente_hasta   date,
    motivo          text,
    created_by      bigint REFERENCES users (id),
    created_at      timestamp(0),
    updated_at      timestamp(0),
    FOREIGN KEY (residencial_id, concepto_id) REFERENCES conceptos_cobro (residencial_id, id),
    FOREIGN KEY (residencial_id, vivienda_id) REFERENCES viviendas (residencial_id, id),
    UNIQUE NULLS NOT DISTINCT (concepto_id, tipo_vivienda, vivienda_id, vigente_desde),
    CHECK (tipo_vivienda IS NULL OR vivienda_id IS NULL),
    CHECK (vivienda_id IS NULL OR motivo IS NOT NULL),
    CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde)
);

-- El UNIQUE evita duplicar cargos si el proceso mensual se repite (HU-17).
CREATE TABLE cargos (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id      bigint NOT NULL,
    vivienda_id         bigint NOT NULL,
    concepto_id         bigint NOT NULL,
    periodo             date NOT NULL CHECK (EXTRACT(DAY FROM periodo) = 1),
    monto               numeric(12, 2) NOT NULL CHECK (monto >= 0),
    fecha_vencimiento   date,
    origen              varchar(20) NOT NULL DEFAULT 'sistema'
                        CHECK (origen IN ('sistema', 'manual', 'migracion')),
    lote_migracion_id   bigint,
    created_at          timestamp(0),
    updated_at          timestamp(0),
    FOREIGN KEY (residencial_id, vivienda_id) REFERENCES viviendas (residencial_id, id),
    FOREIGN KEY (residencial_id, concepto_id) REFERENCES conceptos_cobro (residencial_id, id),
    FOREIGN KEY (residencial_id, lote_migracion_id) REFERENCES lotes_migracion (residencial_id, id),
    UNIQUE (vivienda_id, concepto_id, periodo),
    UNIQUE (residencial_id, id)
);

CREATE INDEX cargos_residencial_periodo_index ON cargos (residencial_id, periodo);

-- ===================================================================
-- E05 y E06 · Cobro en efectivo, cierre de caja y transferencias
-- ===================================================================

CREATE TABLE cajas (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id      bigint NOT NULL REFERENCES residenciales (id),
    cobrador_id         bigint NOT NULL REFERENCES users (id),
    estado              varchar(20) NOT NULL DEFAULT 'abierta'
                        CHECK (estado IN ('abierta', 'cerrada')),
    abierta_en          timestamp(0) NOT NULL,
    cerrada_en          timestamp(0),
    cerrada_por         bigint REFERENCES users (id),
    total_registrado    numeric(12, 2),
    monto_entregado     numeric(12, 2),
    diferencia          numeric(12, 2) GENERATED ALWAYS AS (monto_entregado - total_registrado) STORED,
    justificacion       text,
    created_at          timestamp(0),
    updated_at          timestamp(0),
    UNIQUE (residencial_id, id),
    CHECK (estado = 'abierta'
           OR (cerrada_en IS NOT NULL AND cerrada_por IS NOT NULL
               AND total_registrado IS NOT NULL AND monto_entregado IS NOT NULL)),
    -- Toda diferencia en el cierre debe justificarse (HU-21).
    CHECK (estado = 'abierta' OR monto_entregado = total_registrado OR justificacion IS NOT NULL)
);

CREATE UNIQUE INDEX cajas_una_abierta_por_cobrador_unique
    ON cajas (cobrador_id)
    WHERE estado = 'abierta';

-- Solo el estado 'confirmado' reduce el saldo de la vivienda (HU-24 a HU-27).
CREATE TABLE pagos (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id          bigint NOT NULL,
    vivienda_id             bigint NOT NULL,
    forma_pago              varchar(20) NOT NULL CHECK (forma_pago IN ('efectivo', 'transferencia')),
    estado                  varchar(30) NOT NULL
                            CHECK (estado IN ('confirmado', 'pendiente_verificacion',
                                              'reportado_por_vecino', 'rechazado', 'anulado')),
    origen                  varchar(20) NOT NULL DEFAULT 'sistema'
                            CHECK (origen IN ('sistema', 'portal', 'migracion')),
    monto                   numeric(12, 2) NOT NULL CHECK (monto > 0),
    fecha_pago              date NOT NULL,
    -- La aplicación asigna el consecutivo; varchar admite los recibos migrados.
    numero_recibo           varchar(30),
    caja_id                 bigint,
    registrado_por          bigint REFERENCES users (id),
    banco                   varchar(100),
    numero_referencia       varchar(60),
    cuenta_receptora        varchar(60),
    comprobante_path        varchar(255),
    verificado_por          bigint REFERENCES users (id),
    verificado_en           timestamp(0),
    motivo_rechazo          text,
    anulado_por             bigint REFERENCES users (id),
    anulacion_aprobada_por  bigint REFERENCES users (id),
    anulado_en              timestamp(0),
    motivo_anulacion        text,
    lote_migracion_id       bigint,
    created_at              timestamp(0),
    updated_at              timestamp(0),
    FOREIGN KEY (residencial_id, vivienda_id) REFERENCES viviendas (residencial_id, id),
    FOREIGN KEY (residencial_id, caja_id) REFERENCES cajas (residencial_id, id),
    FOREIGN KEY (residencial_id, lote_migracion_id) REFERENCES lotes_migracion (residencial_id, id),
    UNIQUE (residencial_id, numero_recibo),
    UNIQUE (residencial_id, id),
    CHECK (forma_pago <> 'transferencia' OR origen = 'migracion'
           OR (banco IS NOT NULL AND numero_referencia IS NOT NULL)),
    CHECK (estado <> 'rechazado' OR motivo_rechazo IS NOT NULL),
    CHECK (estado <> 'anulado' OR (anulado_por IS NOT NULL AND anulado_en IS NOT NULL
                                   AND motivo_anulacion IS NOT NULL)),
    -- Quien aprueba una anulación debe ser otro directivo (HU-23).
    CHECK (anulacion_aprobada_por IS NULL OR anulacion_aprobada_por <> anulado_por)
);

CREATE INDEX pagos_vivienda_estado_index ON pagos (vivienda_id, estado);
CREATE INDEX pagos_residencial_fecha_index ON pagos (residencial_id, fecha_pago);
CREATE INDEX pagos_caja_id_index ON pagos (caja_id);

-- Una transferencia rechazada o anulada puede volver a registrarse (HU-24).
CREATE UNIQUE INDEX pagos_referencia_banco_unique
    ON pagos (residencial_id, lower(banco), numero_referencia)
    WHERE numero_referencia IS NOT NULL AND estado NOT IN ('rechazado', 'anulado');

