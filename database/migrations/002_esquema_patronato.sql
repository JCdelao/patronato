CREATE INDEX vehiculos_vivienda_id_index ON vehiculos (vivienda_id);

CREATE UNIQUE INDEX vehiculos_placa_activa_unique
    ON vehiculos (residencial_id, upper(placa))
    WHERE activo;

CREATE TABLE vehiculo_conductores (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id  bigint NOT NULL,
    vehiculo_id     bigint NOT NULL,
