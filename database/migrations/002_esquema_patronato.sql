    nombre          varchar(150),
    created_at      timestamp(0),
    FOREIGN KEY (residencial_id, vehiculo_id) REFERENCES vehiculos (residencial_id, id),
    FOREIGN KEY (residencial_id, residente_id) REFERENCES residentes (residencial_id, id),
