CREATE TABLE medios_entrada (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id  bigint NOT NULL REFERENCES residenciales (id),
    nombre          varchar(40) NOT NULL,
    requiere_placa  boolean NOT NULL DEFAULT false,
    activo          boolean NOT NULL DEFAULT true,
    UNIQUE (residencial_id, nombre),
    UNIQUE (residencial_id, id)
);

CREATE TABLE preautorizaciones (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id      bigint NOT NULL,
    vivienda_id         bigint NOT NULL,
    residente_id        bigint NOT NULL,
    medio_entrada_id    bigint,
    nombre_visitante    varchar(150) NOT NULL,
    inicio              timestamp(0) NOT NULL,
    fin                 timestamp(0) NOT NULL,
    qr_token            uuid UNIQUE,
    created_at          timestamp(0),
    updated_at          timestamp(0),
    FOREIGN KEY (residencial_id, vivienda_id) REFERENCES viviendas (residencial_id, id),
    FOREIGN KEY (residencial_id, residente_id) REFERENCES residentes (residencial_id, id),
    FOREIGN KEY (residencial_id, medio_entrada_id) REFERENCES medios_entrada (residencial_id, id),
    UNIQUE (residencial_id, id),
    CHECK (fin > inicio)
);

CREATE INDEX preautorizaciones_vivienda_inicio_index ON preautorizaciones (vivienda_id, inicio);

CREATE TABLE autorizados_frecuentes (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id  bigint NOT NULL REFERENCES residenciales (id),
    nombre          varchar(150) NOT NULL,
    identidad       varchar(30),
    tipo            varchar(40) NOT NULL,
    -- ISO 8601: 1 = lunes ... 7 = domingo.
    dias_semana     smallint[] NOT NULL CHECK (dias_semana <@ ARRAY[1, 2, 3, 4, 5, 6, 7]::smallint[]),
    hora_inicio     time(0) NOT NULL,
    hora_fin        time(0) NOT NULL,
    activo          boolean NOT NULL DEFAULT true,
    created_by      bigint REFERENCES users (id),
    created_at      timestamp(0),
    updated_at      timestamp(0),
    UNIQUE (residencial_id, id)
);

CREATE TABLE autorizado_frecuente_viviendas (
    residencial_id  bigint NOT NULL,
    autorizado_id   bigint NOT NULL,
    vivienda_id     bigint NOT NULL,
    PRIMARY KEY (autorizado_id, vivienda_id),
    FOREIGN KEY (residencial_id, autorizado_id) REFERENCES autorizados_frecuentes (residencial_id, id),
    FOREIGN KEY (residencial_id, vivienda_id) REFERENCES viviendas (residencial_id, id)
);

-- identificador lo genera el dispositivo: evita duplicados al sincronizar sin conexión (HU-42, HU-51).
CREATE TABLE visitas (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id      bigint NOT NULL,
    identificador       uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    vivienda_id         bigint NOT NULL,
    medio_entrada_id    bigint NOT NULL,
    nombre_visitante    varchar(150) NOT NULL,
    identidad           varchar(30),
    motivo              varchar(255),
    placa               varchar(20),
    entrada_en          timestamp(0) NOT NULL,
    salida_en           timestamp(0),
    guardia_entrada_id  bigint NOT NULL,
    guardia_salida_id   bigint,
    preautorizacion_id  bigint,
    autorizado_id       bigint,
    registrada_sin_conexion boolean NOT NULL DEFAULT false,
    created_at          timestamp(0),
    updated_at          timestamp(0),
    FOREIGN KEY (residencial_id, vivienda_id) REFERENCES viviendas (residencial_id, id),
    FOREIGN KEY (residencial_id, medio_entrada_id) REFERENCES medios_entrada (residencial_id, id),
    FOREIGN KEY (residencial_id, guardia_entrada_id) REFERENCES guardias (residencial_id, id),
    FOREIGN KEY (residencial_id, guardia_salida_id) REFERENCES guardias (residencial_id, id),
    FOREIGN KEY (residencial_id, preautorizacion_id) REFERENCES preautorizaciones (residencial_id, id),
    FOREIGN KEY (residencial_id, autorizado_id) REFERENCES autorizados_frecuentes (residencial_id, id),
    CHECK (salida_en IS NULL OR salida_en >= entrada_en)
);

CREATE INDEX visitas_residencial_entrada_index ON visitas (residencial_id, entrada_en);
CREATE INDEX visitas_vivienda_id_index ON visitas (vivienda_id);

CREATE INDEX visitas_dentro_index
    ON visitas (residencial_id)
    WHERE salida_en IS NULL;

