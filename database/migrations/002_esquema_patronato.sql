-- Qué parte de cada pago cubre cada cargo. Lo no aplicado es saldo a favor (HU-28).
CREATE TABLE pago_aplicaciones (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id  bigint NOT NULL,
    pago_id         bigint NOT NULL,
    cargo_id        bigint NOT NULL,
    monto           numeric(12, 2) NOT NULL CHECK (monto > 0),
    created_at      timestamp(0),
    FOREIGN KEY (residencial_id, pago_id) REFERENCES pagos (residencial_id, id),
    FOREIGN KEY (residencial_id, cargo_id) REFERENCES cargos (residencial_id, id),
    UNIQUE (pago_id, cargo_id)
);

CREATE INDEX pago_aplicaciones_cargo_id_index ON pago_aplicaciones (cargo_id);

-- monto negativo reduce la deuda; positivo la aumenta (HU-29).
CREATE TABLE ajustes (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id      bigint NOT NULL,
    vivienda_id         bigint NOT NULL,
    tipo                varchar(20) NOT NULL
                        CHECK (tipo IN ('descuento', 'condonacion', 'correccion')),
    monto               numeric(12, 2) NOT NULL CHECK (monto <> 0),
    fecha               date NOT NULL,
    motivo              text NOT NULL,
    autorizado_por      bigint REFERENCES users (id),
    lote_migracion_id   bigint,
    created_at          timestamp(0),
    updated_at          timestamp(0),
    FOREIGN KEY (residencial_id, vivienda_id) REFERENCES viviendas (residencial_id, id),
    FOREIGN KEY (residencial_id, lote_migracion_id) REFERENCES lotes_migracion (residencial_id, id),
    -- Solo los datos migrados pueden no tener un usuario que autorice.
    CHECK (autorizado_por IS NOT NULL OR lote_migracion_id IS NOT NULL)
);

CREATE INDEX ajustes_vivienda_id_index ON ajustes (vivienda_id);

-- Saldo = cargos - pagos confirmados + ajustes; negativo significa saldo a favor (HU-27).
CREATE VIEW v_saldos_vivienda AS
SELECT
    v.residencial_id,
    v.id AS vivienda_id,
    v.codigo,
    c.total AS total_cargos,
    p.confirmado AS total_pagos_confirmados,
    a.total AS total_ajustes,
    c.total - p.confirmado + a.total AS saldo,
    p.por_verificar AS total_por_verificar
FROM viviendas v
CROSS JOIN LATERAL (
    SELECT COALESCE(SUM(monto), 0) AS total FROM cargos WHERE vivienda_id = v.id
) c
CROSS JOIN LATERAL (
    SELECT
        COALESCE(SUM(monto) FILTER (WHERE estado = 'confirmado'), 0) AS confirmado,
        COALESCE(SUM(monto) FILTER (WHERE estado IN ('pendiente_verificacion', 'reportado_por_vecino')), 0) AS por_verificar
    FROM pagos WHERE vivienda_id = v.id
) p
CROSS JOIN LATERAL (
    SELECT COALESCE(SUM(monto), 0) AS total FROM ajustes WHERE vivienda_id = v.id
) a;

-- ===================================================================
-- E08 · Ingresos, egresos y presupuesto
-- ===================================================================

CREATE TABLE categorias_financieras (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id  bigint NOT NULL REFERENCES residenciales (id),
    tipo            varchar(10) NOT NULL CHECK (tipo IN ('ingreso', 'egreso')),
    nombre          varchar(100) NOT NULL,
    activa          boolean NOT NULL DEFAULT true,
    created_at      timestamp(0),
    updated_at      timestamp(0),
    UNIQUE (residencial_id, tipo, nombre),
    UNIQUE (residencial_id, id)
);

CREATE TABLE egresos (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id      bigint NOT NULL,
    categoria_id        bigint NOT NULL,
    fecha               date NOT NULL,
    concepto            varchar(255) NOT NULL,
    proveedor           varchar(150),
    monto               numeric(12, 2) NOT NULL CHECK (monto > 0),
    forma_pago          varchar(30),
    numero_comprobante  varchar(60) NOT NULL,
    factura_path        varchar(255),
    estado              varchar(20) NOT NULL DEFAULT 'vigente' CHECK (estado IN ('vigente', 'anulado')),
    motivo_anulacion    text,
    registrado_por      bigint REFERENCES users (id),
    created_at          timestamp(0),
    updated_at          timestamp(0),
    FOREIGN KEY (residencial_id, categoria_id) REFERENCES categorias_financieras (residencial_id, id),
    CHECK (estado <> 'anulado' OR motivo_anulacion IS NOT NULL)
);

CREATE INDEX egresos_residencial_fecha_index ON egresos (residencial_id, fecha);

-- pago_id se llena en los ingresos automáticos por cuotas confirmadas (HU-32).
CREATE TABLE ingresos (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id      bigint NOT NULL,
    categoria_id        bigint NOT NULL,
    pago_id             bigint UNIQUE,
    fecha               date NOT NULL,
    concepto            varchar(255) NOT NULL,
    monto               numeric(12, 2) NOT NULL CHECK (monto > 0),
    numero_comprobante  varchar(60),
    estado              varchar(20) NOT NULL DEFAULT 'vigente' CHECK (estado IN ('vigente', 'anulado')),
    motivo_anulacion    text,
    registrado_por      bigint REFERENCES users (id),
    created_at          timestamp(0),
    updated_at          timestamp(0),
    FOREIGN KEY (residencial_id, categoria_id) REFERENCES categorias_financieras (residencial_id, id),
    FOREIGN KEY (residencial_id, pago_id) REFERENCES pagos (residencial_id, id),
    CHECK (estado <> 'anulado' OR motivo_anulacion IS NOT NULL)
);

CREATE INDEX ingresos_residencial_fecha_index ON ingresos (residencial_id, fecha);

CREATE TABLE presupuestos (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id  bigint NOT NULL,
    categoria_id    bigint NOT NULL,
    anio            smallint NOT NULL,
    monto           numeric(12, 2) NOT NULL CHECK (monto >= 0),
    created_at      timestamp(0),
    updated_at      timestamp(0),
    FOREIGN KEY (residencial_id, categoria_id) REFERENCES categorias_financieras (residencial_id, id),
    UNIQUE (categoria_id, anio)
);

