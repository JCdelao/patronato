);

CREATE INDEX vehiculo_conductores_vehiculo_id_index ON vehiculo_conductores (vehiculo_id);

CREATE TABLE stickers (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
