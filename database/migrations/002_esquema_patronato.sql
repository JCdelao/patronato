-- Esquema del Sistema Integral de Gestión Digital del Patronato (HU-01 a HU-61).
--
-- Ejecutar conectado a la base "patronato" con el usuario "patronato_app",
-- después de "php artisan migrate" (usa la tabla users de Laravel).
-- Si algo falla, nada queda aplicado: ejecutar ROLLBACK, corregir y repetir.
--
-- Convenciones:
--   * Las claves foráneas compuestas (residencial_id, x_id) impiden que un registro
--     apunte a datos de otro residencial (HU-02).
--   * Las fechas se guardan como timestamp(0), igual que las tablas de Laravel.
--   * Lo financiero no se borra: se anula con motivo y queda en auditoria.

BEGIN;

-- Permite impedir turnos superpuestos por guardia (HU-39).
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ===================================================================
-- E01 · Plataforma multi-residencial
-- ===================================================================

CREATE TABLE residenciales (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      varchar(150) NOT NULL UNIQUE,
    direccion   varchar(255),
    telefono    varchar(30),
    correo      varchar(255),
    logo_path   varchar(255),
    estado      varchar(20) NOT NULL DEFAULT 'activo'
                CHECK (estado IN ('activo', 'suspendido')),
    created_at  timestamp(0),
    updated_at  timestamp(0)
);

CREATE TABLE configuracion_residencial (
    residencial_id                  bigint PRIMARY KEY REFERENCES residenciales (id),
    dias_gracia                     smallint NOT NULL DEFAULT 0 CHECK (dias_gracia >= 0),
    meses_tolerancia                smallint NOT NULL DEFAULT 0 CHECK (meses_tolerancia >= 0),
    permite_abono_parcial           boolean NOT NULL DEFAULT false,
    permite_saldo_favor             boolean NOT NULL DEFAULT false,
    doble_control_transferencias    boolean NOT NULL DEFAULT false,
    acceso_depende_pago             boolean NOT NULL DEFAULT false,
    pendiente_cuenta_al_dia         boolean NOT NULL DEFAULT false,
    max_intentos_login              smallint NOT NULL DEFAULT 5,
    minutos_bloqueo_login           smallint NOT NULL DEFAULT 15,
    minutos_inactividad_sesion      smallint NOT NULL DEFAULT 30,
    updated_at                      timestamp(0)
);

-- ===================================================================
-- E02 · Usuarios, permisos y seguridad
-- ===================================================================

CREATE TABLE roles (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo  varchar(40) NOT NULL UNIQUE,
    nombre  varchar(80) NOT NULL
);

ALTER TABLE users
    ADD COLUMN residencial_id          bigint REFERENCES residenciales (id),
    ADD COLUMN rol_id                  bigint REFERENCES roles (id),
    ADD COLUMN activo                  boolean NOT NULL DEFAULT true,
    ADD COLUMN debe_cambiar_password   boolean NOT NULL DEFAULT false;

CREATE INDEX users_residencial_id_index ON users (residencial_id);

-- Matriz de permisos de cada residencial (HU-07).
CREATE TABLE rol_permisos (
    residencial_id  bigint NOT NULL REFERENCES residenciales (id),
    rol_id          bigint NOT NULL REFERENCES roles (id),
    modulo          varchar(40) NOT NULL,
    accion          varchar(20) NOT NULL
                    CHECK (accion IN ('ver', 'registrar', 'verificar', 'aprobar', 'anular')),
    PRIMARY KEY (residencial_id, rol_id, modulo, accion)
);

-- Bitácora de auditoría (HU-08). También cubre el historial de cambios (HU-13),
-- suspensiones de residenciales (HU-03) e intentos de acceso denegado (HU-02).
CREATE TABLE auditoria (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id  bigint REFERENCES residenciales (id),
    user_id         bigint REFERENCES users (id),
    modulo          varchar(40) NOT NULL,
    accion          varchar(40) NOT NULL,
    entidad         varchar(60),
    entidad_id      bigint,
    valor_anterior  jsonb,
    valor_nuevo     jsonb,
    motivo          text,
    ip_address      varchar(45),
    created_at      timestamp(0) NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

CREATE INDEX auditoria_filtros_index ON auditoria (residencial_id, created_at);
CREATE INDEX auditoria_entidad_index ON auditoria (entidad, entidad_id);

CREATE FUNCTION auditoria_inmutable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'La bitácora de auditoría no se puede modificar ni eliminar';
END;
$$;

CREATE TRIGGER auditoria_sin_cambios
    BEFORE UPDATE OR DELETE ON auditoria
    FOR EACH ROW EXECUTE FUNCTION auditoria_inmutable();

CREATE TRIGGER auditoria_sin_truncate
    BEFORE TRUNCATE ON auditoria
    FOR EACH STATEMENT EXECUTE FUNCTION auditoria_inmutable();

-- ===================================================================
-- E15 · Migración de datos históricos
-- (va antes porque cargos, pagos y ajustes referencian el lote)
-- ===================================================================

CREATE TABLE lotes_migracion (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    residencial_id          bigint NOT NULL REFERENCES residenciales (id),
    tipo                    varchar(20) NOT NULL
                            CHECK (tipo IN ('analisis', 'prueba', 'definitiva')),
    estado                  varchar(20) NOT NULL DEFAULT 'pendiente'
                            CHECK (estado IN ('pendiente', 'procesado', 'aprobado', 'importado', 'revertido')),
    archivo_nombre          varchar(255) NOT NULL,
    archivo_sha256          char(64) NOT NULL,
    informe_calidad         jsonb,
    reporte_conciliacion    jsonb,
    correcciones            text,
    ejecutado_por           bigint REFERENCES users (id),
    aprobado_tesorero_por   bigint REFERENCES users (id),
    aprobado_fiscal_por     bigint REFERENCES users (id),
    ejecutado_en            timestamp(0),
    created_at              timestamp(0),
    updated_at              timestamp(0),
    UNIQUE (residencial_id, id),
    -- La importación definitiva necesita a tesorero y fiscal (HU-60).
    CHECK (tipo <> 'definitiva' OR estado NOT IN ('aprobado', 'importado')
           OR (aprobado_tesorero_por IS NOT NULL
               AND aprobado_fiscal_por IS NOT NULL
               AND aprobado_tesorero_por <> aprobado_fiscal_por))
);

CREATE TABLE migracion_errores (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id             bigint NOT NULL REFERENCES lotes_migracion (id) ON DELETE CASCADE,
    linea               integer,
    registro_original   text NOT NULL,
    motivo              varchar(255) NOT NULL,
    created_at          timestamp(0)
);

CREATE INDEX migracion_errores_lote_id_index ON migracion_errores (lote_id);

-- ===================================================================
-- E03 · Viviendas y residentes
-- ===================================================================

CREATE TABLE viviendas (
